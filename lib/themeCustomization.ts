export function createDefaultThemeCustomizations(): Record<
  ThemeId,
  ThemeCustomization
> {
  return Object.fromEntries(
    THEMES.map(({ id }) => [
      id,
      {
        backgroundColor:
          BACKGROUND_COLORS[id] ??
          (createLayout(id, 1, 1080, 1350).background === "gradient"
            ? "#c5c4f3"
            : createLayout(id, 1, 1080, 1350).background),
        backgroundCustomized: false,
        gapColor: null,
        sectionColor: null,
        accentColor: ACCENT_COLORS[id] ?? "#435847",
        smoothEffect: { enabled: false, size: 40, color: "#dce7e0" },
      },
    ]),
  ) as Record<ThemeId, ThemeCustomization>;
}

function layer(
  id: string,
  text: string,
  x: number,
  y: number,
  size: number,
  color: string,
  fontFamily: string,
  options: Partial<CanvasTextLayer> = {},
): CanvasTextLayer {
  return {
    id,
    text,
    x,
    y,
    size,
    color,
    fontFamily,
    bold: false,
    italic: false,
    align: "center",
    background: false,
    backgroundColor: "#ffffff",
    ...options,
  };
}

