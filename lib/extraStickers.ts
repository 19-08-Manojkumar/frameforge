import type { StickerKind } from "@/types/collage";
import type { StickerDefinition } from "@/lib/stickers";

/** Two-ink vector art shares the same editable colors and export engine. */
function art(
  id: StickerKind,
  name: string,
  color: string,
  secondary: string,
  body: string,
  detail: string,
  lines?: string,
): StickerDefinition {
  return {
    id,
    name,
    color,
    secondary,
    paths: [
      { d: body, fill: "primary" },
      { d: detail, fill: "secondary" },
      ...(lines ? [{ d: lines, stroke: "primary" as const, width: 1.3 }] : []),
    ],
  };
}

