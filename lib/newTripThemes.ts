function text(
  id: string,
  value: string,
  x: number,
  y: number,
  size: number,
  color: string,
  width: number,
  font: string,
  options: Partial<CanvasTextLayer> = {},
): CanvasTextLayer {
  return {
    id,
    text: value,
    x,
    y,
    width,
    size,
    color,
    fontFamily: font,
    align: "left",
    bold: false,
    italic: false,
    background: false,
    backgroundColor: "#ffffff",
    ...options,
  };
}
