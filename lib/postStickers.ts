import type { StickerKind } from "@/types/collage";
import type { StickerDefinition, StickerPath } from "@/lib/stickers";

const circle = (x: number, y: number, r: number) =>
  `M${x + r} ${y}A${r} ${r} 0 1 1 ${x - r} ${y}A${r} ${r} 0 1 1 ${x + r} ${y}Z`;
const pin = (x: number, y: number) =>
  `M${x} ${y}C${x - 6} ${y - 7} ${x + 6} ${y - 7} ${x} ${y}Z`;
function route(
  id: StickerKind,
  name: string,
  line: string,
  start: [number, number],
  end: [number, number],
  terrain?: string,
  detail?: string,
): StickerDefinition {
  const paths: StickerPath[] = [];
  if (terrain) paths.push({ d: terrain, fill: "secondary" });
  if (detail) paths.push({ d: detail, stroke: "primary", width: 0.8 });
  paths.push(
    { d: line, stroke: "primary", width: 1.4, dash: [0.12, 1.9] },
    {
      d: circle(...start, 1.6),
      fill: "secondary",
      stroke: "primary",
      width: 1,
    },
    { d: pin(...end), fill: "primary" },
    { d: circle(end[0], end[1] - 3.6, 0.65), fill: "secondary" },
  );
  return {
    id,
    name,
    color: "#477769",
    secondary: "#ead9b4",
    category: "Trip routes",
    keywords:
      "trip tour travel route journey map pointer dotted dashed trail itinerary start destination hiking trekking adventure",
    paths,
  };
}
function art(
  id: StickerKind,
  name: string,
  category: string,
  color: string,
  secondary: string,
  body: string,
  detail: string,
  lines?: string,
): StickerDefinition {
  return {
    id,
    name,
    category,
    color,
    secondary,
    paths: [
      { d: body, fill: "primary" },
      { d: detail, fill: "secondary" },
      ...(lines ? [{ d: lines, stroke: "primary" as const, width: 1.2 }] : []),
    ],
  };
}

